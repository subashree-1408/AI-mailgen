import React from 'react';
import { Sparkles, X, Check } from 'lucide-react';

interface SubjectAlternativesModalProps {
  isOpen: boolean;
  onClose: () => void;
  alternatives: string[];
  currentSubject: string;
  onSelect: (subject: string) => void;
  loading: boolean;
}

export const SubjectAlternativesModal: React.FC<SubjectAlternativesModalProps> = ({
  isOpen,
  onClose,
  alternatives,
  currentSubject,
  onSelect,
  loading,
}) => {
  if (!isOpen) return null;

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/40 backdrop-blur-xs">
      <div className="bg-white rounded-2xl shadow-xl border border-slate-200 max-w-md w-full overflow-hidden animate-in fade-in zoom-in-95 duration-150">
        <div className="px-5 py-4 border-b border-slate-100 flex items-center justify-between">
          <div className="flex items-center space-x-2">
            <Sparkles className="w-4 h-4 text-indigo-600" />
            <h3 className="font-semibold text-slate-900 text-sm">AI Subject Line Alternatives</h3>
          </div>
          <button
            onClick={onClose}
            className="text-slate-400 hover:text-slate-600 p-1 rounded-lg hover:bg-slate-100"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        <div className="p-5 space-y-3">
          <p className="text-xs text-slate-500">
            Select a high-converting alternative subject line generated by Gemini:
          </p>

          {loading ? (
            <div className="py-8 flex flex-col items-center justify-center space-y-2 text-slate-500 text-xs">
              <div className="w-5 h-5 border-2 border-indigo-600 border-t-transparent rounded-full animate-spin" />
              <span>Generating alternative subjects with Gemini...</span>
            </div>
          ) : (
            <div className="space-y-2">
              {alternatives.map((alt, idx) => {
                const isCurrent = alt.trim().toLowerCase() === currentSubject.trim().toLowerCase();
                return (
                  <button
                    key={idx}
                    type="button"
                    onClick={() => {
                      onSelect(alt);
                      onClose();
                    }}
                    className={`w-full text-left p-3 rounded-xl border text-xs transition-all flex items-center justify-between group ${
                      isCurrent
                        ? 'border-indigo-500 bg-indigo-50/60 font-semibold text-indigo-900'
                        : 'border-slate-200 hover:border-indigo-300 hover:bg-slate-50 text-slate-700'
                    }`}
                  >
                    <span className="flex-1 pr-2">{alt}</span>
                    {isCurrent ? (
                      <Check className="w-4 h-4 text-indigo-600 flex-shrink-0" />
                    ) : (
                      <span className="text-[11px] font-medium text-slate-400 group-hover:text-indigo-600">
                        Use
                      </span>
                    )}
                  </button>
                );
              })}
            </div>
          )}
        </div>

        <div className="px-5 py-3 bg-slate-50 border-t border-slate-100 flex justify-end">
          <button
            type="button"
            onClick={onClose}
            className="px-4 py-1.5 text-xs font-medium text-slate-600 hover:bg-slate-200/60 rounded-lg"
          >
            Close
          </button>
        </div>
      </div>
    </div>
  );
};
